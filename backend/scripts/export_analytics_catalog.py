"""Generate the human-readable catalogue from the same definitions as the API."""

from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))
from modules.feature_metrics.domain.analysis.catalog import DEFINITIONS
from modules.feature_metrics.domain.analysis.models import ANALYSIS_VERSION, GROUPS

target = ROOT / "docs/architecture/f1-metric-catalog.md"
rows = [
    "# F1 metric catalogue",
    "",
    "For strategy development, start with the [67 decision-oriented strategy calculations](strategy-metric-catalog.md) and [strategy architecture/methods runbook](10-strategy-foundation.md). This catalogue documents the retained general diagnostics API; it is not the default strategy feature set.",
    "",
    f"Generated by `backend/scripts/export_analytics_catalog.py`. Version: `{ANALYSIS_VERSION}`. {len(DEFINITIONS)} calculated metrics.",
    "",
    "Definitions are also available from authenticated `GET /api/feature-metrics/analytics/catalog`.",
    "See [calculation contracts and extension runbook](09-f1-analytics.md) for sampling, formulas, evidence limits and testing.",
    "",
]
for group in GROUPS:
    definitions = [item for item in DEFINITIONS.values() if item.group == group]
    rows.extend(
        [
            f"## {group.title()} ({len(definitions)})",
            "",
            "| ID | Unit | Scope | Interpretation | Inputs | Definition |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
    )
    for definition in definitions:
        rows.append(
            f"| `{definition.metric_id}` | {definition.unit} | {definition.scope} | {definition.interpretation} | {', '.join(definition.required_inputs)} | {definition.description.replace('|','/')} |"
        )
    rows.append("")
target.write_text("\n".join(rows), encoding="utf-8")
print(f"Exported {len(DEFINITIONS)} metrics to {target.name}")
