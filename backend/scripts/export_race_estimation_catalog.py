"""Keep the detailed model catalogue synchronized with executable definitions."""

import argparse
from pathlib import Path
from modules.feature_metrics.domain.race_estimation.catalog import (
    DEFINITIONS,
    GROUP_INPUTS,
    GROUP_USES,
    MODEL_NOTES,
)
from modules.feature_metrics.domain.race_estimation.models import (
    MODEL_VERSION,
    ModelAssumptions,
)


def render():
    lines = [
        "# Race estimation calculation catalogue",
        "",
        f"Version `{MODEL_VERSION}`. **{len(DEFINITIONS)} model definitions**. Generated by `backend/scripts/export_race_estimation_catalog.py`.",
        "",
        "The existing 137 general metrics and 67 strategy definitions remain available. This catalogue adds composable physical scenarios and panel snapshots; overlapping concepts are not additional independent measurements.",
        "",
        "[Architecture, exact algorithms, assumptions, limitations and extension runbook](12-race-estimation.md).",
        "",
        "`observed` = source observation, `derived` = numerical calculation, `scenario` = explicit physical/strategy assumptions, `index` = uncalibrated relative score. Unavailable inputs produce null values, not synthetic observations. Support is evidence coverage and heuristic evidence strength, never a calibrated event probability.",
        "",
    ]
    for group in GROUP_INPUTS:
        lines += [
            "## " + group.replace("_", " ").title(),
            "",
            "**Required inputs:** " + "; ".join(GROUP_INPUTS[group]) + ".",
            "",
            "**Consumer / purpose:** " + GROUP_USES[group],
            "",
            "| ID | Label | Unit | Method | Calculation |",
            "| --- | --- | --- | --- | --- |",
        ]
        for key, definition in DEFINITIONS.items():
            if definition["group"] == group:
                lines.append(
                    f"| `{key}` | {definition['label']} | {definition['unit']} | {definition['method']} | {definition['formula'].replace('|', '/')} |"
                )
        lines.append("")
    lines += ["## Default assumptions", "", "| Parameter | Default |", "| --- | --- |"]
    lines += [
        f"| `{key}` | {value if value is not None else 'Not calibrated'} |"
        for key, value in ModelAssumptions().model_dump().items()
    ]
    lines += ["", "## Interpretation limits", ""] + [
        "- " + note for note in MODEL_NOTES
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = (
        Path(__file__).resolve().parents[2]
        / "docs/architecture/race-estimation-catalog.md"
    )
    text = render()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            raise SystemExit("Race estimation catalogue is out of date")
    else:
        target.write_text(text, encoding="utf-8")
    print(
        f"{len(DEFINITIONS)} race-estimation definitions: {'verified' if args.check else 'exported'}"
    )
