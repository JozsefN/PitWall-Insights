"""Generate the strategy catalogue from executable contracts, not a second hand-maintained metric list."""

from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))
from modules.feature_metrics.domain.strategy.catalog import DEFINITIONS
from modules.feature_metrics.domain.strategy.models import STRATEGY_VERSION

target = ROOT / "docs/architecture/strategy-metric-catalog.md"
lines = [
    "# Strategy calculation catalogue",
    "",
    f"Version `{STRATEGY_VERSION}`. **{len(DEFINITIONS)} decision-oriented calculations**, generated by `backend/scripts/export_strategy_catalog.py`.",
    "",
    "These are the primary strategy primitives. [Architecture, exact methods, worked examples and extension runbook](10-strategy-foundation.md). Existing generic diagnostic statistics remain in [the compatibility catalogue](f1-metric-catalog.md).",
    "",
    "Every value has an event-time cutoff, entry/pair/session scope, units, evidence and availability. `estimated` and `assumed` are never displayed as direct measurements. A percentage is a documented fraction or an evidence-backed conditional probability, never a renamed confidence score.",
    "",
]
for name in dict.fromkeys(definition.group for definition in DEFINITIONS.values()):
    definitions = [row for row in DEFINITIONS.values() if row.group == name]
    lines.extend(
        [
            f"## {name.replace('_',' ').title()}",
            "",
            f"**Required inputs:** {', '.join(definitions[0].requires)}.",
            "",
            f"**Interpretation limits:** {definitions[0].limitations}",
            "",
            "| ID | Scope | Unit | Calculation | Strategy/user use |",
            "| --- | --- | --- | --- | --- |",
        ]
    )
    for row in definitions:
        lines.append(
            f"| `{row.metric_id}` | {row.scope} | {row.unit} | {row.formula.replace('|','/')} | {row.use.replace('|','/')} |"
        )
    lines.append("")
lines.extend(
    [
        "## Implementations and dependencies",
        "",
        "| Layer | Code | Consumers |",
        "| --- | --- | --- |",
        "| Pace and identifiability | `feature_metrics/domain/strategy/pace.py` | Rival forecasts, tyre calibration review, scenario baseline |",
        "| Matched gaps, spatial distances | `feature_metrics/domain/strategy/rivals.py` | Catch estimates, pit windows, rejoin order |",
        "| Pit costs and counterfactuals | `feature_metrics/domain/strategy/pits.py` | Rival-specific opportunities and scenario pit cost |",
        "| Car state and wind physics | `feature_metrics/domain/strategy/spatial.py` | Incident context, airflow inputs, geometry readiness |",
        "| Historical probability | `feature_metrics/domain/strategy/risk.py`, `history.py` | Conditional risk display and future stochastic planner inputs |",
        "| Survey alignment | `feature_metrics/domain/strategy/georegistration.py` | Verified north/coordinate transformation before wind/spatial use |",
        "| Bounded strategy search | `decision_engine/domain/strategy_planner.py` | Conditional best modeled plan and near-optimal stop window |",
        "",
    ]
)
target.write_text("\n".join(lines), encoding="utf-8")
print(f"Exported {len(DEFINITIONS)} strategy definitions")
